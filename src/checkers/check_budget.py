#!/usr/bin/env python3
"""check_budget.py — enforce token budgets on the always-on instruction set.

GENERATED by create-context-hygiene. Do not hand-edit.

Three levels, because a file can pass its own total while one section balloons,
and a whole manifest can balloon while every file passes:

  per-section   each `#`-heading section against `max_section`
  per-file      each manifest entry against its `budget`
  total         every always-on file summed against `total_ceiling`

The total is the number that actually matters — it is the tax paid on every
turn whether or not the turn needs any of it — and it includes the `@path`
files CLAUDE.md pulls in, which no per-file check would ever see.

Warn at `warn_pct`, fail at `fail_pct`; exit non-zero only on a fail, so there
is runway before a hard stop.

    check_budget.py [--counter X] [--json] [--all-sections] [--root DIR]
    check_budget.py --init [--template FILE] [--headroom 1.25] [--force]
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from count_tokens import COUNTERS, count, count_file  # noqa: E402
from hygiene_env import (  # noqa: E402
    CANDIDATE_ALWAYS_ON,
    CONFIG_NAME,
    budget_settings,
    discover_imports,
    find_config,
    load_config,
    rel,
    resolve_repo_root,
    split_sections,
    warn,
)

OK, WARN, FAIL = "ok", "warn", "FAIL"


def _status(tokens: int, limit: int | None, warn_pct: int, fail_pct: int) -> tuple[str, float | None]:
    if not limit:
        return OK, None
    pct = 100.0 * tokens / limit
    if pct >= fail_pct:
        return FAIL, pct
    if pct >= warn_pct:
        return WARN, pct
    return OK, pct


# ---------------------------------------------------------------------------
# Analysis
# ---------------------------------------------------------------------------
def analyze(root: Path, cfg: dict, counter: str, model: str) -> dict:
    b = budget_settings(cfg)
    warn_pct, fail_pct = int(b["warn_pct"]), int(b["fail_pct"])
    entries = cfg.get("always_on", []) or []

    files: list[dict] = []
    resolved_paths: list[Path] = []

    for entry in entries:
        raw = entry.get("path")
        if not raw:
            continue
        path = (root / raw).resolve()
        if not path.is_file():
            files.append({"path": raw, "missing": True, "tokens": 0,
                          "budget": entry.get("budget"), "status": OK, "sections": []})
            continue
        resolved_paths.append(path)
        files.append(_analyze_file(
            path, root, counter, model,
            budget=entry.get("budget"),
            max_section=int(entry.get("max_section", b["max_section"]) or 0),
            warn_pct=warn_pct, fail_pct=fail_pct,
            source="manifest",
        ))

    # The hidden tax: files CLAUDE.md @-imports are loaded every turn too.
    for path in discover_imports(resolved_paths, root):
        files.append(_analyze_file(
            path, root, counter, model,
            budget=None, max_section=int(b["max_section"] or 0),
            warn_pct=warn_pct, fail_pct=fail_pct,
            source="import",
        ))

    total = sum(f["tokens"] for f in files)
    ceiling = int(b["total_ceiling"] or 0)
    total_status, total_pct = _status(total, ceiling, warn_pct, fail_pct)

    return {
        "root": str(root),
        "counter": counter,
        "warn_pct": warn_pct,
        "fail_pct": fail_pct,
        "files": files,
        "total": {"tokens": total, "ceiling": ceiling,
                  "pct": total_pct, "status": total_status},
        "failed": total_status == FAIL or any(
            f["status"] == FAIL or any(s["status"] == FAIL for s in f["sections"])
            for f in files
        ),
    }


def _analyze_file(path: Path, root: Path, counter: str, model: str, *,
                  budget, max_section: int, warn_pct: int, fail_pct: int,
                  source: str) -> dict:
    text = path.read_text(encoding="utf-8")
    tokens = count(text, counter, model=model)
    status, pct = _status(tokens, budget, warn_pct, fail_pct)

    sections = []
    for sec in split_sections(text):
        own = count(sec.own, counter, model=model)
        sub = count(sec.subtree, counter, model=model) if sec.level else own
        s_status, s_pct = _status(own, max_section, warn_pct, fail_pct)
        sections.append({
            "path": sec.path, "line": sec.heading_line, "level": sec.level,
            "tokens": own, "subtree_tokens": sub, "limit": max_section,
            "pct": s_pct, "status": s_status,
        })

    return {"path": rel(path, root), "missing": False, "source": source,
            "tokens": tokens, "budget": budget, "pct": pct, "status": status,
            "max_section": max_section, "sections": sections}


# ---------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------
def render(report: dict, show_all_sections: bool) -> None:
    pad = "{:<44}{:>9}{:>9}{:>7}  {}"
    print(f"Context budget — {report['root']}   (counter: {report['counter']})\n")
    print(pad.format("FILE", "TOKENS", "BUDGET", "%", "STATUS"))
    print("-" * 78)

    for f in report["files"]:
        if f["missing"]:
            print(pad.format(f["path"], "—", "—", "—", "missing (not on disk)"))
            continue
        label = f["path"] + ("  (@import)" if f.get("source") == "import" else "")
        print(pad.format(
            label[:43],
            f"{f['tokens']:,}",
            f"{f['budget']:,}" if f["budget"] else "—",
            f"{f['pct']:.0f}%" if f["pct"] is not None else "—",
            f["status"],
        ))
        for s in f["sections"]:
            if not show_all_sections and s["status"] == OK:
                continue
            if not s["tokens"]:
                continue  # an empty parent heading is noise, never a finding
            # The leaf title, indented by depth. The full ancestor path is in
            # --json; in a fixed-width column it truncates every row to the H1
            # and tells you nothing about which section is the fat one.
            leaf = s["path"].rsplit(" > ", 1)[-1]
            name = ("  " + "  " * max(s["level"] - 1, 0)
                    + "#" * max(s["level"], 1) + " " + leaf)[:43]
            print(pad.format(
                name,
                f"{s['tokens']:,}",
                f"{s['limit']:,}" if s["limit"] else "—",
                f"{s['pct']:.0f}%" if s["pct"] is not None else "—",
                f"{s['status']} (section, line {s['line']})",
            ))

    t = report["total"]
    print("-" * 78)
    print(pad.format(
        "TOTAL always-on",
        f"{t['tokens']:,}",
        f"{t['ceiling']:,}" if t["ceiling"] else "—",
        f"{t['pct']:.0f}%" if t["pct"] is not None else "—",
        t["status"],
    ))

    if report["failed"]:
        print("\nOver budget. Move the flagged content per docs/PLACEMENT.md — a "
              "kernel rule stays, a procedure becomes a skill, a lookup becomes a "
              "reference doc.")


# ---------------------------------------------------------------------------
# --init
# ---------------------------------------------------------------------------
def _round_up(n: int, step: int = 100) -> int:
    return int(math.ceil(n / step) * step) if n else step


def init_config(root: Path, template: Path | None, counter: str, model: str,
                headroom: float, force: bool) -> int:
    """Write a starter manifest seeded from the target's *current* counts.

    Budgets derived from what the repo already loads start realistic, which is
    the difference between a check that gets adopted and one that gets disabled
    on its first run. The flip side is that a bloated repo seeds a bloated
    budget — the emitted file says so, and says to ratchet it down.
    """
    dest = find_config(root)
    if dest.exists() and not force:
        print(f"{rel(dest, root)} exists — preserved (use --force to re-seed)")
        return 0

    found: list[tuple[str, int, int]] = []  # (relpath, tokens, largest section)
    for cand in CANDIDATE_ALWAYS_ON:
        p = root / cand
        if not p.is_file():
            continue
        text = p.read_text(encoding="utf-8")
        tokens = count(text, counter, model=model)
        biggest = max((count(s.own, counter, model=model)
                       for s in split_sections(text)), default=0)
        found.append((cand, tokens, biggest))

    total = sum(t for _, t, _ in found)
    ceiling = _round_up(int(total * headroom), 500) or 6000
    default_max_section = _round_up(
        int(max((b for _, _, b in found), default=0) * headroom), 100) or 800

    lines = []
    for cand, tokens, biggest in found:
        lines.append("")
        lines.append("[[always_on]]")
        lines.append(f'path        = "{cand}"')
        lines.append(f"budget      = {_round_up(int(tokens * headroom))}"
                     f"    # currently {tokens:,} tokens")
        lines.append(f"max_section = {_round_up(int(biggest * headroom)) or 800}"
                     f"    # largest section is currently {biggest:,}")
    entries = "\n".join(lines) if lines else (
        "\n# No always-on files found. Add an entry per file that is loaded every\n"
        "# turn, e.g.:\n#\n# [[always_on]]\n# path   = \"CLAUDE.md\"\n# budget = 3000\n"
    )

    if template and template.is_file():
        body = template.read_text(encoding="utf-8")
    else:
        body = _FALLBACK_TEMPLATE

    body = (body
            .replace("{{COUNTER}}", counter)
            .replace("{{MODEL}}", model)
            .replace("{{TOTAL_CEILING}}", str(ceiling))
            .replace("{{MAX_SECTION}}", str(default_max_section))
            .replace("{{ALWAYS_ON_ENTRIES}}", entries))

    dest.write_text(body, encoding="utf-8")
    print(f"Wrote {rel(dest, root)}  "
          f"({len(found)} always-on file(s), {total:,} tokens today, "
          f"ceiling {ceiling:,})")
    if found:
        print("Budgets are seeded from current counts with "
              f"{int((headroom - 1) * 100)}% headroom — they describe today, not "
              "the target. Ratchet them down as content moves out.")
    return 0


_FALLBACK_TEMPLATE = """\
# .context-budget.toml — the always-on context manifest.
[budget]
counter       = "{{COUNTER}}"
model         = "{{MODEL}}"
warn_pct      = 80
fail_pct      = 100
total_ceiling = {{TOTAL_CEILING}}
max_section   = {{MAX_SECTION}}
{{ALWAYS_ON_ENTRIES}}
"""


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------
def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Check always-on token budgets.")
    ap.add_argument("--root", type=Path, default=None)
    ap.add_argument("--counter", choices=COUNTERS, default=None,
                    help="override the counter set in .context-budget.toml")
    ap.add_argument("--model", default=None)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--all-sections", action="store_true",
                    help="list every section, not only the ones over budget")
    ap.add_argument("--quiet", action="store_true",
                    help="one summary line while passing; the full report on a failure")
    ap.add_argument("--init", action="store_true",
                    help=f"write a starter {CONFIG_NAME} seeded from current counts")
    ap.add_argument("--template", type=Path, default=None)
    ap.add_argument("--headroom", type=float, default=1.25)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)

    root = (args.root or resolve_repo_root()).resolve()
    cfg = load_config(find_config(root))
    b = budget_settings(cfg)
    counter = args.counter or b["counter"]
    model = args.model or b["model"]

    if args.init:
        return init_config(root, args.template, counter, model,
                           args.headroom, args.force)

    if not cfg:
        warn(f"no {CONFIG_NAME} at {root} — run: check_budget.py --init")
        return 2
    if not cfg.get("always_on"):
        warn(f"{CONFIG_NAME} lists no [[always_on]] entries — nothing to check")
        return 0

    report = analyze(root, cfg, counter, model)
    if args.json:
        print(json.dumps(report, indent=2))
    elif args.quiet and not report["failed"]:
        t = report["total"]
        pct = f"{t['pct']:.0f}%" if t["pct"] is not None else "—"
        print(f"context-hygiene: {t['tokens']:,} always-on tokens "
              f"across {len(report['files'])} file(s), {pct} of ceiling — ok")
    else:
        render(report, args.all_sections)
    return 1 if report["failed"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
