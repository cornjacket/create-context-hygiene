#!/usr/bin/env python3
"""count_tokens.py — measure tokens, not lines.

GENERATED by create-context-hygiene. Do not hand-edit.

The currency of an always-on instruction file is **tokens loaded per turn**. A
markdown table or a fenced code block costs far more than its line count
suggests, so every check in this toolkit measures tokens through the one
interface below.

Three backends, one signature:

  heuristic  (default)  chars/4, with a denser divisor inside fenced code.
                        Zero dependencies, instant — this is what gates the
                        inner loop (pre-commit).
  tiktoken              local BPE (o200k_base). Closer to Claude than the
                        heuristic; falls back to heuristic with a warning if
                        the package is not importable.
  anthropic             messages.count_tokens — exact, needs network + a key.
                        For CI or an on-demand authoritative reading.

Because the offline tiers approximate, **set budgets with headroom** (design
§2.1 suggests ~70% of the true ceiling) so approximation error can never make a
check flap between passing and failing.

CLI:
    count_tokens.py FILE [FILE...] [--counter heuristic|tiktoken|anthropic]
    count_tokens.py --calibrate FILE [FILE...]     # backend error table
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

try:
    from hygiene_env import iter_lines, warn
except ImportError:  # running from a checkout without the package on sys.path
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from hygiene_env import iter_lines, warn

COUNTERS = ("heuristic", "tiktoken", "anthropic")
DEFAULT_MODEL = "claude-opus-5"

# Characters per token. Prose sits near 4; fenced code tokenizes denser because
# punctuation, indentation, and identifiers fragment. Calibrate with
# --calibrate on your own corpus before trusting either figure precisely.
CHARS_PER_TOKEN_PROSE = 4.0
CHARS_PER_TOKEN_CODE = 2.9

_tiktoken_enc = None
_tiktoken_failed = False
_anthropic_envelope: int | None = None


# ---------------------------------------------------------------------------
# Public interface
# ---------------------------------------------------------------------------
def count(text: str, counter: str = "heuristic", *, model: str = DEFAULT_MODEL) -> int:
    """Return the token count of `text` under the named backend."""
    if not text:
        return 0
    if counter == "heuristic":
        return _heuristic(text)
    if counter == "tiktoken":
        return _tiktoken(text, model=model)
    if counter == "anthropic":
        return _anthropic(text, model=model)
    raise ValueError(f"unknown counter: {counter!r} (expected one of {COUNTERS})")


def count_file(path, counter: str = "heuristic", *, model: str = DEFAULT_MODEL) -> int:
    return count(Path(path).read_text(encoding="utf-8"), counter, model=model)


# ---------------------------------------------------------------------------
# Backends
# ---------------------------------------------------------------------------
def _heuristic(text: str) -> int:
    prose_chars = 0
    code_chars = 0
    for _lineno, line, in_fence in iter_lines(text):
        n = len(line) + 1  # + the newline
        if in_fence:
            code_chars += n
        else:
            prose_chars += n
    total = prose_chars / CHARS_PER_TOKEN_PROSE + code_chars / CHARS_PER_TOKEN_CODE
    return max(1, round(total))


def _tiktoken(text: str, *, model: str) -> int:
    global _tiktoken_enc, _tiktoken_failed
    if _tiktoken_enc is None and not _tiktoken_failed:
        try:
            import tiktoken
            _tiktoken_enc = tiktoken.get_encoding("o200k_base")
        except Exception as exc:  # noqa: BLE001 - any import/download failure
            _tiktoken_failed = True
            warn(f"tiktoken unavailable ({exc}); falling back to the heuristic counter")
    if _tiktoken_enc is None:
        return _heuristic(text)
    return len(_tiktoken_enc.encode(text))


def _anthropic(text: str, *, model: str) -> int:
    """Exact count via the Anthropic API.

    `messages.count_tokens` counts a *message*, so the figure includes a small
    fixed envelope around the content. We measure that envelope once and
    subtract it, which keeps this backend directly comparable to the two
    text-only tokenizers above (and therefore to a budget set with either).
    """
    global _anthropic_envelope
    try:
        import anthropic
    except ImportError:
        raise SystemExit(
            "error: the 'anthropic' counter needs the anthropic SDK.\n"
            "       pip install anthropic   (and export ANTHROPIC_API_KEY)"
        )

    client = anthropic.Anthropic()

    def _raw(payload: str) -> int:
        resp = client.messages.count_tokens(
            model=model,
            messages=[{"role": "user", "content": payload}],
        )
        return resp.input_tokens

    if _anthropic_envelope is None:
        # " " is one token; whatever else the call reports is the envelope.
        _anthropic_envelope = max(0, _raw(" ") - 1)
    return max(0, _raw(text) - _anthropic_envelope)


def available_counters() -> list[str]:
    """Which backends can actually run here, cheapest first."""
    out = ["heuristic"]
    try:
        import tiktoken  # noqa: F401
        out.append("tiktoken")
    except ImportError:
        pass
    try:
        import anthropic  # noqa: F401
        import os
        if os.environ.get("ANTHROPIC_API_KEY"):
            out.append("anthropic")
    except ImportError:
        pass
    return out


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------
def _calibrate(paths: list[Path], model: str) -> int:
    """Report each backend's reading, and its error against the best available.

    The point is not the table; it is the headroom decision. If the heuristic
    reads 12% low on your corpus, a budget set at the true ceiling will let a
    file over the line unnoticed — set it lower by at least that margin.
    """
    backends = available_counters()
    reference = backends[-1]
    if reference == "heuristic":
        warn("only the heuristic counter is available — install tiktoken, or set "
             "ANTHROPIC_API_KEY, to measure its error against a real tokenizer")

    print(f"Calibration — reference backend: {reference}\n")
    header = f"{'FILE':<40}" + "".join(f"{b:>12}" for b in backends)
    print(header)
    print("-" * len(header))

    errors: list[float] = []
    for p in paths:
        text = Path(p).read_text(encoding="utf-8")
        counts = {b: count(text, b, model=model) for b in backends}
        row = f"{str(p)[:39]:<40}" + "".join(f"{counts[b]:>12,}" for b in backends)
        print(row)
        ref = counts[reference]
        if ref and reference != "heuristic":
            errors.append(100.0 * (counts["heuristic"] - ref) / ref)

    if errors:
        lo, hi = min(errors), max(errors)
        mean = sum(errors) / len(errors)
        print(f"\nheuristic vs {reference}: mean {mean:+.1f}%  "
              f"(range {lo:+.1f}% .. {hi:+.1f}%)")
        print("Set budgets with at least this much headroom — an approximation that "
              "reads low is a check that silently passes an over-budget file.")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Count tokens in one or more files.")
    ap.add_argument("files", nargs="+", type=Path)
    ap.add_argument("--counter", choices=COUNTERS, default="heuristic")
    ap.add_argument("--model", default=DEFAULT_MODEL,
                    help=f"model for the anthropic counter (default: {DEFAULT_MODEL})")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--calibrate", action="store_true",
                    help="compare every available backend and report the error band")
    args = ap.parse_args(argv)

    missing = [p for p in args.files if not p.is_file()]
    if missing:
        for p in missing:
            print(f"error: no such file: {p}", file=sys.stderr)
        return 2

    if args.calibrate:
        return _calibrate(args.files, args.model)

    results = {str(p): count_file(p, args.counter, model=args.model) for p in args.files}
    if args.json:
        print(json.dumps({"counter": args.counter, "files": results,
                          "total": sum(results.values())}, indent=2))
    elif len(results) == 1:
        print(next(iter(results.values())))
    else:
        for path, n in results.items():
            print(f"{n:>8,}  {path}")
        print(f"{sum(results.values()):>8,}  TOTAL")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
