def resolve_repo_root(start: str | os.PathLike | None = None) -> Path:
    """Resolve the repo root from `start` (default: this file's directory).

    Primary: `git rev-parse --show-toplevel`, which for a LINKED WORKTREE
    correctly returns the worktree root, not the .bare container.

    Fallback (no git, or not a repo): walk up looking for a repo marker. Note
    `.git` may be a FILE (a linked worktree's `gitdir:` pointer) or a DIRECTORY
    — `Path.exists()` matches both; an `is_dir()` check would silently miss
    every worktree.
    """
    here = Path(start) if start else Path(__file__).resolve().parent
    here = here.resolve()

    try:
        out = subprocess.run(
            ["git", "-C", str(here), "rev-parse", "--show-toplevel"],
            capture_output=True, text=True, check=False,
        )
        if out.returncode == 0 and out.stdout.strip():
            return Path(out.stdout.strip()).resolve()
    except (OSError, subprocess.SubprocessError):
        pass

    for d in [here, *here.parents]:
        if (d / ".git").exists() or (d / CONFIG_NAME).exists():
            return d
    return here


