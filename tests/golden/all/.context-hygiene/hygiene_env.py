# 4. @-import discovery
# ---------------------------------------------------------------------------
IMPORT_RE = re.compile(r"(?:^|[\s(])@([\w./~@-]+)")


def discover_imports(entry_paths, root: Path) -> list[Path]:
    """Resolve `@path` references transitively, in document order.

    Claude Code auto-loads what CLAUDE.md pulls in via `@path`, so those files
    are part of the always-on tax even though no manifest entry names them.

    False positives (an email address, a Python decorator in prose) are filtered
    by the cheapest possible test: the referenced file has to exist. Matches
    inside fenced code blocks are skipped — a snippet showing `@foo/bar.md` is
    documentation, not an import.
    """
    seen: set[Path] = {Path(p).resolve() for p in entry_paths}
    found: list[Path] = []
    queue = [Path(p) for p in entry_paths]

    while queue:
        src = queue.pop(0)
        if not src.is_file():
            continue
        try:
            text = src.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        for _lineno, line, in_fence in iter_lines(text):
            if in_fence:
                continue
            for ref in IMPORT_RE.findall(line):
                for base in (src.parent, root):
                    cand = (base / ref.lstrip("/")).expanduser()
                    if cand.is_file():
                        resolved = cand.resolve()
                        if resolved not in seen:
                            seen.add(resolved)
                            found.append(resolved)
                            queue.append(resolved)
                        break
    return found


