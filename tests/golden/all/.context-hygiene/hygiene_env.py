def _strip_comment(line: str) -> str:
    """Drop a trailing `#` comment, ignoring `#` inside a quoted string."""
    out, quote = [], None
    for ch in line:
        if quote:
            out.append(ch)
            if ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
            out.append(ch)
        elif ch == "#":
            break
        else:
            out.append(ch)
    return "".join(out)


def _parse_value(v: str):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        return v[1:-1]
    if v in ("true", "false"):
        return v == "true"
    try:
        return int(v)
    except ValueError:
        pass
    try:
        return float(v)
    except ValueError:
        return v


def _parse_toml_minimal(text: str) -> dict:
    """A parser for the narrow schema this generator writes — nothing more.

    Python 3.11 shipped `tomllib`; targets on 3.9/3.10 would otherwise need a
    dependency for a config file we generate ourselves. Handles `[table]`,
    `[[array-of-table]]`, and scalar key = value. Anything fancier belongs in
    tomllib, and on a modern interpreter that is what runs.
    """
    data: dict = {}
    cur: dict = data
    for raw in text.splitlines():
        line = _strip_comment(raw).strip()
        if not line:
            continue
        if line.startswith("[["):
            name = line[2:line.index("]]")].strip()
            arr = data.setdefault(name, [])
            cur = {}
            arr.append(cur)
        elif line.startswith("["):
            name = line[1:line.index("]")].strip()
            cur = data.setdefault(name, {})
        elif "=" in line:
            k, _, v = line.partition("=")
            cur[k.strip()] = _parse_value(v)
    return data


# ---------------------------------------------------------------------------
# 3. Section tree
# ---------------------------------------------------------------------------
HEADING_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
FENCE_RE = re.compile(r"^\s*(```+|~~~+)")


@dataclass
class Section:
    level: int          # 0 for the pre-heading preamble
    title: str
    path: str           # "## A > ### B"
    heading_line: int   # 1-indexed; 0 for the preamble
    start_line: int     # first line of own body
    end_line: int       # last line of own body (inclusive)
    own: str = ""       # body text excluding child sections
    subtree: str = ""   # heading + body + every descendant
    children: list = field(default_factory=list)


def iter_lines(text: str):
    """Yield (lineno, line, in_fence). `in_fence` is True inside a fenced block
    and on its closing delimiter, False on the opening one."""
    fence: str | None = None
    for i, line in enumerate(text.splitlines(), start=1):
        m = FENCE_RE.match(line)
        if fence is None:
            if m:
                fence = m.group(1)[:3]
                yield i, line, False
                continue
            yield i, line, False
        else:
            closing = m and m.group(1).startswith(fence)
            yield i, line, True
            if closing:
                fence = None


def split_sections(text: str) -> list[Section]:
    """Split into a flat, document-ordered list of sections with `path` set.

    A simple line splitter, per design §2.2 — no markdown AST. `own` is the
    section's own body; `subtree` is the section plus everything nested under
    it, so a thin parent full of fat children reports both honestly.
    """
    lines = text.splitlines()
    marks: list[tuple[int, int, str]] = []  # (index0, level, title)
    for lineno, line, in_fence in iter_lines(text):
        if in_fence:
            continue
        m = HEADING_RE.match(line)
        if m:
            marks.append((lineno - 1, len(m.group(1)), m.group(2).strip()))

    sections: list[Section] = []
    stack: list[Section] = []

    def push(sec: Section):
        while stack and stack[-1].level >= sec.level:
            stack.pop()
        if stack:
            stack[-1].children.append(sec)
        prefix = stack[-1].path + " > " if stack else ""
        sec.path = prefix + sec.title if sec.level else sec.title
        stack.append(sec)
        sections.append(sec)

    first = marks[0][0] if marks else len(lines)
    if first > 0 and "".join(lines[:first]).strip():
        pre = Section(0, "(preamble)", "(preamble)", 0, 1, first)
        pre.own = "\n".join(lines[:first])
        pre.subtree = pre.own
        sections.append(pre)

    for n, (idx, level, title) in enumerate(marks):
        body_end = marks[n + 1][0] if n + 1 < len(marks) else len(lines)
        sub_end = len(lines)
        for later_idx, later_level, _ in marks[n + 1:]:
            if later_level <= level:
                sub_end = later_idx
                break
        sec = Section(level, title, title, idx + 1, idx + 2, body_end)
        sec.own = "\n".join(lines[idx + 1:body_end])
        sec.subtree = "\n".join(lines[idx:sub_end])
        push(sec)

    return sections


