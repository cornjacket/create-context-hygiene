#!/usr/bin/env python3
"""context_lint.py — the procedural-smell detector.

GENERATED by create-context-hygiene. Do not hand-edit.

Roughly 80% of always-on bloat is detectable without an LLM, because bloat has
a *shape*: fenced commands, long step lists, wide lookup tables, oversized
sections. This lints for that shape and names the bucket the content belongs in
(docs/PLACEMENT.md), so a finding says *where to move it*, not merely that
something is too big.

It flags shape, never meaning. A genuinely load-bearing code block in a kernel
will be flagged; that is a judgement call for a human, and the LLM audit skill
is the half of the job this deliberately does not attempt.

    context_lint.py [--root DIR] [--json] [--warn-only]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from count_tokens import COUNTERS, count  # noqa: E402
from hygiene_env import (  # noqa: E402
    CONFIG_NAME,
    budget_settings,
    discover_imports,
    find_config,
    iter_lines,
    lint_settings,
    load_config,
    rel,
    resolve_repo_root,
    split_sections,
    warn,
)

# smell -> (bucket, why). The bucket names are the three from PLACEMENT.md.
SMELLS = {
    "code-block": ("skill|reference",
                   "a fenced block is how-to or reference material, not a rule"),
    "step-sequence": ("skill",
                      "an ordered list of steps is a procedure — needed while doing "
                      "task X, not on every turn"),
    "reference-table": ("reference",
                        "a wide table is consulted, not obeyed"),
    "oversized-section": ("split|move",
                          "too large to be a kernel rule; split it or move it out"),
    "command-dump": ("skill",
                     "a run of shell invocations is a procedure"),
}

ORDERED_RE = re.compile(r"^\s{0,3}\d+[.)]\s+\S")
TABLE_RE = re.compile(r"^\s{0,3}\|")
SHELL_RE = re.compile(
    r"^\s{0,3}(?:\$\s+\S"
    r"|(?:sudo|git|npm|npx|yarn|pnpm|make|cd|export|curl|wget|bash|sh|zsh"
    r"|python3?|pip3?|uv|docker|kubectl|terraform|gh|brew)\s+\S)"
)
FENCE_OPEN_RE = re.compile(r"^\s*(?:```+|~~~+)")


def lint_text(text: str, cfg_lint: dict, counter: str, model: str) -> list[dict]:
    findings: list[dict] = []
    max_section_tokens = int(cfg_lint["max_section_tokens"] or 0)

    for sec in split_sections(text):
        body = sec.own
        if not body.strip():
            continue
        base = sec.start_line - 1  # absolute line number of body line 0

        def add(smell: str, line: int, detail: str):
            bucket, why = SMELLS[smell]
            findings.append({
                "section": sec.path, "line": line, "smell": smell,
                "suggested_bucket": bucket, "detail": detail, "why": why,
            })

        # --- oversized section
        if max_section_tokens:
            tokens = count(body, counter, model=model)
            if tokens > max_section_tokens:
                add("oversized-section", sec.heading_line or 1,
                    f"{tokens:,} tokens (limit {max_section_tokens:,})")

        # --- fenced code block
        if cfg_lint.get("code_block", True):
            prev_fence = False
            for lineno, line, in_fence in iter_lines(body):
                if in_fence and not prev_fence:
                    add("code-block", base + lineno, "fenced code block")
                    break
                prev_fence = in_fence

        # --- runs of ordered-list items / table rows / shell lines
        #
        # Each rule is a run counter that fires exactly once, on the line that
        # pushes the run over its threshold. Firing on "run is still >= N" would
        # report the same list once per trailing blank line.
        n_steps = int(cfg_lint["max_ordered_list_items"])
        n_shell = int(cfg_lint["max_shell_lines"])
        run_ordered = run_table = run_shell = 0
        start_ordered = start_table = start_shell = 0

        for lineno, line, in_fence in iter_lines(body):
            if in_fence or FENCE_OPEN_RE.match(line):
                # Fenced content is already reported as `code-block`; counting
                # its lines again as steps or commands is double-reporting.
                if run_table:
                    _flush_table(add, run_table, start_table, cfg_lint)
                run_ordered = run_table = run_shell = 0
                start_ordered = start_table = start_shell = 0
                continue

            abs_line = base + lineno
            blank = not line.strip()
            # An indented line continues the item above; steps that wrap onto a
            # second line are the common case, not the end of the list.
            continuation = line.startswith(("  ", "\t"))

            if ORDERED_RE.match(line):
                run_ordered += 1
                start_ordered = start_ordered or abs_line
                if run_ordered == n_steps:
                    add("step-sequence", start_ordered,
                        f"ordered list of {n_steps}+ items")
            elif not blank and not continuation:
                run_ordered, start_ordered = 0, 0

            if TABLE_RE.match(line):
                run_table += 1
                start_table = start_table or abs_line
            elif run_table:
                _flush_table(add, run_table, start_table, cfg_lint)
                run_table, start_table = 0, 0

            if SHELL_RE.match(line):
                run_shell += 1
                start_shell = start_shell or abs_line
                if run_shell == n_shell:
                    add("command-dump", start_shell,
                        f"{n_shell}+ consecutive shell lines")
            elif not blank:
                run_shell, start_shell = 0, 0

        if run_table:
            _flush_table(add, run_table, start_table, cfg_lint)

    findings.sort(key=lambda f: f["line"])
    return findings


def _flush_table(add, run_len: int, start: int, cfg_lint: dict) -> None:
    rows = max(0, run_len - 2)  # header + separator are not data rows
    limit = int(cfg_lint["max_table_rows"])
    if rows > limit:
        add("reference-table", start, f"table with {rows} rows (limit {limit})")


# ---------------------------------------------------------------------------
def collect_targets(root: Path, cfg: dict) -> list[Path]:
    paths: list[Path] = []
    for entry in cfg.get("always_on", []) or []:
        p = (root / entry.get("path", "")).resolve()
        if p.is_file():
            paths.append(p)
    return paths + discover_imports(paths, root)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Flag procedural smells in always-on docs.")
    ap.add_argument("--root", type=Path, default=None)
    ap.add_argument("--counter", choices=COUNTERS, default=None)
    ap.add_argument("--model", default=None)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--warn-only", action="store_true",
                    help="always exit 0 (overrides lint.warn_only)")
    ap.add_argument("--quiet", action="store_true",
                    help="one summary line unless the findings are failing the run")
    args = ap.parse_args(argv)

    root = (args.root or resolve_repo_root()).resolve()
    cfg = load_config(find_config(root))
    if not cfg:
        warn(f"no {CONFIG_NAME} at {root} — run: check_budget.py --init")
        return 2

    b = budget_settings(cfg)
    lint_cfg = lint_settings(cfg)
    counter = args.counter or b["counter"]
    model = args.model or b["model"]

    results = []
    for path in collect_targets(root, cfg):
        text = path.read_text(encoding="utf-8")
        for f in lint_text(text, lint_cfg, counter, model):
            results.append({"file": rel(path, root), **f})

    warn_only = args.warn_only or bool(lint_cfg.get("warn_only"))

    if args.json:
        print(json.dumps({"root": str(root), "warn_only": warn_only,
                          "findings": results}, indent=2))
    elif args.quiet and (warn_only or not results):
        # Never silent when there is something to say: a warn-only run still
        # reports the count, because findings nobody sees are findings nobody
        # acts on. It just does not bury a passing commit in the full list.
        if results:
            noun = "finding" if len(results) == 1 else "findings"
            script = rel(Path(__file__).resolve(), root)
            print(f"context-hygiene: {len(results)} placement {noun} (warn-only) "
                  f"— run `python3 {script}` for the list")
        else:
            print("context-hygiene: no placement findings — ok")
    else:
        _render(results, root, warn_only)

    return 0 if (warn_only or not results) else 1


def _render(results: list[dict], root: Path, warn_only: bool) -> None:
    if not results:
        print(f"context-lint — {root}\n\nNo procedural smells found.")
        return

    print(f"context-lint — {root}\n")
    current = None
    for f in results:
        if f["file"] != current:
            current = f["file"]
            print(f"{current}")
        print(f"  {current}:{f['line']}  {f['smell']}  →  {f['suggested_bucket']}")
        print(f"      section: {f['section']}")
        print(f"      {f['detail']} — {f['why']}")
    noun = "finding" if len(results) == 1 else "findings"
    print(f"\n{len(results)} {noun}. Buckets are defined in docs/PLACEMENT.md.")
    if warn_only:
        print("(warn-only: not failing the run)")


if __name__ == "__main__":
    raise SystemExit(main())
